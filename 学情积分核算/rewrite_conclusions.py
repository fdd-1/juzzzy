def main():
    src = Path(r"C:\Users\fengjianyi\Desktop\学情积分核算\_doc.xml").read_text(encoding="utf-8")

    # 替换每节 callout
    import re
    SECTIONS = [
        ("4.1 服务指标跟进 &amp; 语义分析", "4.1"),
        ("4.2 组班多意向占比", "4.2"),
        ("4.3 群发消息汇总", "4.3"),
        ("4.4 停课学员执行监控", "4.4"),
        ("4.5 服务月跟进", "4.5"),
        ("4.6 系统电话外呼 &amp; 微信回复监控", "4.6"),
    ]
    for h3_title, key in SECTIONS:
        # 匹配该节的 <h3>...</h3><callout ...>...</callout>
        pattern = re.compile(
            r'(<h3>' + re.escape(h3_title) + r'</h3>)<callout[^>]*>.*?</callout>',
            re.DOTALL
        )
        new_block = "<h3>" + h3_title + "</h3>" + CALLOUT[key]
        src_new = pattern.sub(new_block, src, count=1)
        if src_new == src:
            print(f"[WARN] {key} 没替换成功")
        else:
            src = src_new
            print(f"[OK] {key} 已替换")

    # 写到新文件供 review
    out = Path(r"C:\Users\fengjianyi\Desktop\学情积分核算\_doc_v2.xml")
    out.write_text(src, encoding="utf-8")
    print(f"\n已写到 {out}")
    print(f"size: {out.stat().st_size}")

    # 嵌入文档
    print("\n嵌入文档...")
    r = subprocess.run([LARK_CLI, "docs", "+update", "--api-version", "v2",
                        "--doc", DOC_ID, "--command", "overwrite",
                        "--doc-format", "xml", "--content", "-"],
                       capture_output=True, text=True, encoding="utf-8",
                       shell=False, timeout=300, input=src)
    try:
        resp = json.loads(r.stdout)
        print(f"  result={resp.get('data',{}).get('result')}")
    except:
        print(f"  output: {r.stdout[:300]}")

    print(f"\n文档：https://hcnig43mb8gp.feishu.cn/docx/{DOC_ID}")


if __name__ == "__main__":
    main()
